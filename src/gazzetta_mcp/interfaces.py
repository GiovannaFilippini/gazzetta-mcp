"""Contracts between the replaceable parts. Implementations live in sources/, parsing/, cache/."""

from __future__ import annotations

from datetime import date
from typing import Protocol

from .models import (
    Atto,
    Feed,
    NormattivaLink,
    RawPage,
    SearchFilters,
    SearchHit,
    Serie,
    Sommario,
)


class SourceClient(Protocol):
    """Network access to the GU. Rate limited, identifies itself, never bulk-downloads."""

    async def get_feed(self, serie: Serie) -> RawPage: ...
    async def get_elenco_30giorni(self, serie: Serie) -> RawPage: ...
    async def get_sommario(self, data: date, serie: Serie, numero: int) -> RawPage: ...
    async def get_atto_scheda(self, codice: str, data: date, serie: Serie) -> RawPage: ...
    async def get_atto_testo(
        self, codice: str, data: date, serie: Serie, tipo: str | None
    ) -> RawPage: ...
    def url_sommario(self, data: date, serie: Serie, numero: int) -> str: ...
    def url_atto(self, codice: str, data: date, serie: Serie) -> str: ...
    def url_pdf(self, data: date, serie: Serie, numero: int) -> str: ...


class Parser(Protocol):
    """Pure functions: bytes in, models out. No network, no cache."""

    def parse_feed(self, raw: bytes, serie: Serie) -> Feed: ...
    def parse_sommario(
        self, raw: bytes, serie: Serie, data: date, numero: int, base_url: str
    ) -> Sommario: ...
    def parse_elenco_30giorni(self, raw: bytes) -> list[tuple[date, int]]: ...
    def parse_atto(
        self, scheda: bytes, testo: bytes, codice: str, serie: Serie, data: date, base_url: str
    ) -> Atto: ...


class Cache(Protocol):
    """Local SQLite store with full text search over what the user already requested."""

    def get_feed(self, serie: Serie, max_age_seconds: int) -> Feed | None: ...
    def put_feed(self, feed: Feed) -> None: ...
    def get_sommario(self, data: date, serie: Serie) -> Sommario | None: ...
    def put_sommario(self, sommario: Sommario) -> None: ...
    def get_atto(self, codice: str) -> Atto | None: ...
    def put_atto(self, atto: Atto) -> None: ...
    def search(self, testo: str, filtri: SearchFilters) -> list[SearchHit]: ...
    def get_http(self, url: str, max_age_seconds: int) -> RawPage | None: ...
    def put_http(self, page: RawPage) -> None: ...


class NormattivaLinker(Protocol):
    """Builds the link to the current version on Normattiva. No bulk download in v1."""

    def link_for(self, atto: str) -> NormattivaLink: ...
